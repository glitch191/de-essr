#pragma once

#include "dsp/DeEsserEngine.h"

#include <cstdint>
#include <vector>

/** Synthetic test signals and measurement helpers.

    Everything here is generated by code: there is no recorded audio in the
    repository. The "vowel" is a harmonic tone, the "sibilant" is band-limited
    noise between 5 and 9 kHz.
*/
namespace testsig
{

struct Segment
{
    int start = 0;
    int length = 0;
};

struct Sequence
{
    std::vector<float> samples;
    std::vector<Segment> voiced;
    std::vector<Segment> sibilant;
};

/** Harmonic tone with a falling spectrum (no energy above about 3.4 kHz), unit RMS. */
std::vector<float> vowel (double sampleRate, int numSamples, double fundamentalHz = 140.0);

/** Band-limited noise, unit RMS. */
std::vector<float> bandNoise (double sampleRate, int numSamples, double lowHz, double highHz, std::uint32_t seed);

/** Low sustained chord (energy below 2 kHz) plus a faint steady noise bed, used as a backing track. */
std::vector<float> accompaniment (double sampleRate, int numSamples, std::uint32_t seed);

/** Vowel, sibilant burst, vowel, silence, repeated. The peak of the result is peakDb (dBFS).
    burstRelativeDb is the RMS of the bursts relative to the RMS of the vowels.
*/
Sequence speechLike (double sampleRate, int cycles, float peakDb, float burstRelativeDb = -6.0f);

/** Continuous vowel with sibilant bursts on top of it. */
Sequence overlappedSpeech (double sampleRate, int cycles, float peakDb, float burstRelativeDb);

void scale (std::vector<float>& samples, float gain);
float peak (const std::vector<float>& samples);

/** Energy between two frequencies over a section of a signal (Hann frames of 1024 samples). */
double bandEnergy (const std::vector<float>& samples, int start, int length,
                   double sampleRate, double lowHz, double highHz);

/** Reduction in dB of the band energy between input and output over the given segments.
    The middle of each segment is measured, skipping marginSeconds on each side.
*/
double reductionDb (const std::vector<float>& input, const std::vector<float>& output, int latency,
                    const std::vector<Segment>& segments, int firstSegment,
                    double sampleRate, double lowHz, double highHz, double marginSeconds = 0.03);

/** Runs the engine over whole signals (one vector per channel), in blocks of blockSize. */
std::vector<std::vector<float>> run (deessr::DeEsserEngine& engine,
                                     const std::vector<std::vector<float>>& input, int blockSize);

/** Energy of (output delayed by latency) minus input, relative to the input energy, in dB. */
double residualDb (const std::vector<float>& input, const std::vector<float>& output, int latency);

} // namespace testsig
